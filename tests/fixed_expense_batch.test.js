'use strict';
const assert = require('node:assert/strict');
const { loadApp } = require('./app_harness');
const { createIndexedDB } = require('./idb_harness');
module.exports = async function () {
  const idb = createIndexedDB();
  const a = loadApp(idb).api, b = loadApp(idb).api;
  assert.equal(a.getState().transactions.length, 0);
  await assert.rejects(a.batchPayFixedExpenses([], '2026-10-01'));
  await assert.rejects(a.batchPayFixedExpenses([{ key: 'father_insurance', amount: 1300 }], '2026-10-01'));
  const requests = [a, b].map(api => api.batchPayFixedExpenses([{ key: 'dan_insurance', amount: 2900 }], '2026-10-01'));
  const results = await Promise.allSettled(requests);
  assert.equal(results.filter(r => r.status === 'fulfilled').length, 1, 'only one tab commits');
  assert.equal(results.find(r => r.status === 'fulfilled').value[0].sync_status, 'local_only');
  await assert.rejects(a.batchPayFixedExpenses([{ key: 'dan_insurance', amount: 2900 }], '2026-10-01'));
  idb.failWrites = true;
  await assert.rejects(a.batchPayFixedExpenses([{ key: 'sister_mind', amount: 2000 }], '2026-10-01'));
  idb.failWrites = false;
  assert.equal((await a.batchPayFixedExpenses([{ key: 'sister_mind', amount: 2000 }], '2026-10-01')).length, 1, 'abort leaves no paid marker');
  await assert.rejects(a.batchPayFixedExpenses([{ key: 'sister_mind', amount: 1 }, { key: 'dan_insurance', amount: -1 }], '2026-11-01'));
  assert.equal((await a.batchPayFixedExpenses([{ key: 'sister_mind', amount: 2000 }, { key: 'dan_insurance', amount: 2900 }], '2026-11-01')).length, 2);
  const c = a.fatherInsuranceCycle;
  assert.equal(c(null, '2026-10').status, 'needs_review');
  assert.equal(c({ anchor: '2024-01-31', interval: 1 }, '2024-02').due, '2024-02-29');
  assert.equal(c({ anchor: '2024-01-31', interval: 1 }, '2024-03').due, '2024-03-31');
  assert.equal(c({ anchor: '2025-01-31', interval: 1 }, '2025-02').due, '2025-02-28');
  assert.equal(c({ anchor: '2024-01-31', interval: 1 }, '2024-02', ['2024-02']).due, '2024-03-31');
  await a.automationPreference('father-cycle', { anchor: '2026-01-31', interval: 3 });
  assert.equal((await a.batchPayFixedExpenses([{ key: 'father_insurance', amount: 2600 }], '2026-10-31')).length, 1);
  a.getState().currentUser = { id: 'other' };
  const other = await a.batchPayFixedExpenses([{ key: 'dan_insurance', amount: 2900 }], '2026-10-01');
  assert.equal(other[0].user_id, 'other'); assert.equal(other[0].sync_status, 'pending_sync');
};
