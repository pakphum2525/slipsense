'use strict';
const assert = require('node:assert/strict');
const { loadApp } = require('./app_harness');
module.exports = async function () {
  const { api, el } = loadApp();
  for (const mode of [1300, 2600]) {
    const fresh = loadApp().api;
    const split = await fresh.allocateMonthlySalary({ transaction_date: '2026-12-01', total_salary: 45000, father_insurance_mode: mode });
    const metrics = fresh.calculateDashboardMetrics(split.records, '2026-12');
    assert.equal(metrics.fundBalances.length, 6);
    const balance = bucket => metrics.fundBalances.find(row => row.bucket === bucket).availableBalance;
    assert.equal(balance('fixed_expense'), mode === 1300 ? 9800 : 11100);
    assert.equal(balance('general_expense'), mode === 1300 ? 12800 : 11500);
    assert.equal(balance('dan_insurance'), 2900);
    assert.equal(metrics.totalExpense, 0, 'saving is not a premium payment');
    assert.equal(metrics.insurancePaymentStatus.paidAmount, 0);
    assert.equal(split.records.reduce((sum, row) => sum + Math.round(row.amount * 100), 0), 4500000);
  }
  const invalid = loadApp().api;
  for (const extra of [{ total_salary: 100 }, { total_salary: Infinity }, { dan_insurance: -1 }, { dan_insurance: -0.001 }, { dan_insurance: Infinity }, { investment_stock: NaN }]) {
    await assert.rejects(invalid.allocateMonthlySalary({ transaction_date: '2026-01-01', total_salary: 45000, ...extra }));
  }
  assert.equal(invalid.getState().transactions.length, 0);
  const decimal = await invalid.allocateMonthlySalary({ transaction_date: '2026-01-01', total_salary: 45000.13, investment_stock: 6500.01 });
  assert.equal(decimal.totalAllocated, 45000.13);
  assert.equal((await invalid.automationPreference('salary')).general_expense, 12800.12);
  const old = { version: 1, total_salary: 45000, investment_stock: 6500, home_building: 13000, fixed_expense: 12700, emergency_personal: 0, general_expense: 12800 };
  const higher = api.upgradeSalaryTemplate({ ...old, fixed_expense: 14000, general_expense: 11500 });
  assert.equal(higher.fixed_expense, 11100); assert.equal(higher.dan_insurance, 2900);
  const upgraded = api.upgradeSalaryTemplate(old);
  assert.equal(upgraded.fixed_expense, 9800); assert.equal(upgraded.dan_insurance, 2900);
  assert.equal(upgraded.fixed_expense + upgraded.dan_insurance, old.fixed_expense);
  assert.equal(api.upgradeSalaryTemplate(upgraded), upgraded, 'template upgrade is idempotent');
  assert.equal(api.upgradeSalaryTemplate({ ...old, version: undefined }).needs_review, true);
  assert.equal(api.upgradeSalaryTemplate({ ...old, fixed_expense: 12000 }).needs_review, true);
  const options = { transaction_date: '2026-11-01', total_salary: 45000 };
  assert.equal(await api.automationPreference('salary'), undefined);
  await assert.rejects(api.allocateMonthlySalary({ ...options, general_expense: 1 }));
  assert.equal(await api.automationPreference('salary'), undefined);
  await api.allocateMonthlySalary(options);
  const template = await api.automationPreference('salary');
  assert.equal(template.general_expense, 12800);
  await assert.rejects(api.allocateMonthlySalary(options));
  api.bindAutomationEvents();
  el('btnUseSalaryTemplate').dispatchEvent({ type: 'click' });
  await new Promise(resolve => setTimeout(resolve, 30));
  assert.equal(el('salarySplitTotalInput').value, '45000');
  assert.equal(el('salarySplitModal').hidden, false);
  el('salarySplitFund1Input').value = '7000';
  assert.equal((await api.automationPreference('salary')).investment_stock, 6500, 'draft edits do not mutate template');
  api.getState().currentUser = { id: 'user-b' };
  assert.equal(await api.automationPreference('salary'), undefined);
  await api.allocateMonthlySalary({ ...options, investment_stock: 7000 });
  assert.equal((await api.automationPreference('salary')).investment_stock, 7000);
  await api.automationPreference('salary', null);
  assert.equal(await api.automationPreference('salary'), null);
  api.getState().currentUser = null;
  assert.equal((await api.automationPreference('salary')).investment_stock, 6500);
  const cumulative = loadApp().api;
  await cumulative.allocateMonthlySalary({ transaction_date: '2026-12-01', total_salary: 45000 });
  const rolled = await cumulative.rolloverMonthlySurplusToEmergency('2026-12');
  assert.equal(rolled.amount, 22600);
  assert.equal(rolled.records.some(row => row.fund_bucket === 'dan_insurance'), false);
  await cumulative.allocateMonthlySalary({ transaction_date: '2027-01-01', total_salary: 45000 });
  const beforePayment = cumulative.calculateDashboardMetrics(cumulative.getState().transactions, '2027-01');
  assert.equal(beforePayment.fundBalances.find(row => row.bucket === 'dan_insurance').availableBalance, 5800);
  await cumulative.recordFixedExpenseItem('dan_insurance', { transaction_date: '2027-01-03', amount: 4000 });
  assert.equal(cumulative.calculateDashboardMetrics(cumulative.getState().transactions, '2027-01').fundBalances.find(row => row.bucket === 'dan_insurance').availableBalance, 1800);
  assert.equal(cumulative.calculateDashboardMetrics(cumulative.getState().transactions, '2026-12').fundBalances.find(row => row.bucket === 'dan_insurance').availableBalance, 2900);
  const legacy = loadApp().api;
  await legacy.saveTransaction({ transaction_date: '2026-08-01', merchant: 'legacy', amount: 12700, type: 'income', category: 'salary_income', fund_bucket: 'fixed_expense', note: '[SALARY_SPLIT:2026-08:fixed_expense]' });
  await legacy.saveTransaction({ transaction_date: '2026-08-02', merchant: 'legacy premium', amount: 2900, type: 'expense', category: 'health_medical', fund_bucket: 'fixed_expense', note: '[fixed_item:dan_insurance]' , id: '11111111-1111-4111-8111-111111111111' });
  const netBefore = legacy.calculateDashboardMetrics(legacy.getState().transactions, '2026-08').netBalance;
  await assert.rejects(legacy.rolloverMonthlySurplusToEmergency('2026-08'));
  assert.equal((await legacy.upgradeLegacyInsurance('2026-08')).needs_review, true);
  assert.equal((await legacy.upgradeLegacyInsurance('2026-08', true)).upgraded, true);
  const after = legacy.calculateDashboardMetrics(legacy.getState().transactions, '2026-08');
  assert.equal(after.netBalance, netBefore);
  assert.equal(after.fundBalances.find(row => row.bucket === 'fixed_expense').availableBalance, 9800);
  assert.equal(after.fundBalances.find(row => row.bucket === 'dan_insurance').availableBalance, 0);
  assert.equal((await legacy.upgradeLegacyInsurance('2026-08', true)).upgraded, false);
  await legacy.saveTransaction({ transaction_date: '2026-08-04', merchant: 'ประกันแดน คลุมเครือ', amount: 10, type: 'expense', category: 'health_medical', fund_bucket: 'fixed_expense' });
  assert.equal((await legacy.upgradeLegacyInsurance('2026-08', true)).needs_review, true);
  await assert.rejects(legacy.rolloverMonthlySurplusToEmergency('2026-08'));
  const rolledLegacy = loadApp().api;
  await rolledLegacy.saveTransaction({ transaction_date: '2026-07-01', merchant: 'legacy', amount: 12700, type: 'income', category: 'salary_income', fund_bucket: 'fixed_expense', note: '[SALARY_SPLIT:2026-07:fixed_expense]' });
  await rolledLegacy.saveTransaction({ transaction_date: '2026-07-31', merchant: 'old rollover', amount: 100, type: 'expense', category: 'transfer_other', fund_bucket: 'fixed_expense', note: '[SURPLUS_ROLLOVER_OUT:2026-07:fixed_expense]' });
  assert.equal((await rolledLegacy.upgradeLegacyInsurance('2026-07', true)).needs_review, true, 'rolled month requires manual reconciliation');
  assert.equal(rolledLegacy.getState().transactions.length, 2);
};
