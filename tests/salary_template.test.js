'use strict';
const assert = require('node:assert/strict');
const { loadApp } = require('./app_harness');
module.exports = async function () {
  const { api, el } = loadApp();
  const options = { transaction_date: '2026-11-01', total_salary: 45000 };
  assert.equal(await api.automationPreference('salary'), undefined);
  await assert.rejects(api.allocateMonthlySalary({ ...options, general_expense: 1 }));
  assert.equal(await api.automationPreference('salary'), undefined);
  await api.allocateMonthlySalary(options);
  const template = await api.automationPreference('salary');
  assert.equal(template.general_expense, 12800);
  await assert.rejects(api.allocateMonthlySalary(options));
  api.bindAutomationEvents();
  el('btnUseSalaryTemplate').dispatchEvent({ type: 'click' });
  await new Promise(resolve => setTimeout(resolve, 30));
  assert.equal(el('salarySplitTotalInput').value, '45000');
  assert.equal(el('salarySplitModal').hidden, false);
  el('salarySplitFund1Input').value = '7000';
  assert.equal((await api.automationPreference('salary')).investment_stock, 6500, 'draft edits do not mutate template');
  api.getState().currentUser = { id: 'user-b' };
  assert.equal(await api.automationPreference('salary'), undefined);
  await api.allocateMonthlySalary({ ...options, investment_stock: 7000 });
  assert.equal((await api.automationPreference('salary')).investment_stock, 7000);
  await api.automationPreference('salary', null);
  assert.equal(await api.automationPreference('salary'), null);
  api.getState().currentUser = null;
  assert.equal((await api.automationPreference('salary')).investment_stock, 6500);
};
